        private static string EscC(string s)
        {
            if (string.IsNullOrEmpty(s)) return "";
            return s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\r", "").Replace("\n", "");
        }

        private static string SafeIdent(string s, int fallbackIdx)
        {
            if (string.IsNullOrEmpty(s)) return "custom_" + fallbackIdx;
            var sb = new StringBuilder();
            for (int i = 0; i < s.Length; i++)
            {
                char c = s[i];
                if ((c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_')
                    sb.Append(c);
                else if (c == ' ' || c == '-')
                    sb.Append('_');
            }
            string res = sb.ToString().Trim('_');
            if (string.IsNullOrEmpty(res)) return "custom_" + fallbackIdx;
            if (res[0] >= '0' && res[0] <= '9') res = "m_" + res;
            return res.ToLowerInvariant();
        }

        public static string GenerateUniversalProfileHeader(
            EspChipProfile chip,
            List<PuzzleFeatureItem> features,
            List<PinSlotConfig> slots,
            List<AutomationRuleConfig> rules,
            XioProjectFile meta)
        {
            int maxSlots = Math.Max(1, Math.Min(32, slots != null ? slots.Count : 16));
            int maxRules = Math.Max(1, Math.Min(24, rules != null ? rules.Count : 8));

            var sb = new StringBuilder();
            sb.AppendLine("#pragma once");
            sb.AppendLine("// ============================================================================");
            sb.AppendLine("// AUTO-GENERATED BY XIO UNIVERSAL PUZZLE STUDIO (.EXE)");
            sb.AppendLine(String.Format("// Target Chip : {0} ({1})", chip.Name, chip.Fqbn));
            sb.AppendLine(String.Format("// Slot & Rule : {0} Dynamic Pin Slots / {1} Dynamic Rules", slots != null ? slots.Count : 0, rules != null ? rules.Count : 0));
            sb.AppendLine("// ============================================================================");
            sb.AppendLine();
            sb.AppendLine(String.Format("#define XIO_UNIV_MAX_SLOTS       {0}", maxSlots));
            sb.AppendLine(String.Format("#define XIO_UNIV_MAX_RULES       {0}", maxRules));
            sb.AppendLine();

            bool rulesActive = false;
            foreach (PuzzleFeatureItem f in features)
            {
                if (!string.IsNullOrEmpty(f.UnivMacro))
                {
                    // 100% User Freedom: if user turned it off OR removed it from Active Deck ("Kurangi"), compile it OUT (0)!
                    bool en = f.Enabled && f.InActiveDeck;
                    if (f.RequiresWifi && !chip.HasWifi) en = false;
                    if (f.RequiresBle && !chip.HasBle) en = false;
                    if (f.Key == "rules_engine" && en) rulesActive = true;
                    sb.AppendLine(String.Format("#define {0,-24} {1}", f.UnivMacro, en ? 1 : 0));
                }
            }
            sb.AppendLine(String.Format("#define XIO_U_BUTTON_ACTIONS     {0}", rulesActive ? 1 : 0));

            sb.AppendLine();
            sb.AppendLine(String.Format("#define XIO_U_AP_SSID            \"{0}\"", EscC(meta.ApSsid)));
            sb.AppendLine(String.Format("#define XIO_U_AP_PASS            \"{0}\"", EscC(meta.ApPass)));
            sb.AppendLine(String.Format("#define XIO_U_STA_SSID           \"{0}\"", EscC(meta.StaSsid)));
            sb.AppendLine(String.Format("#define XIO_U_STA_PASS           \"{0}\"", EscC(meta.StaPass)));
            sb.AppendLine(String.Format("#define XIO_U_MQTT_HOST          \"{0}\"", EscC(meta.MqttHost)));
            sb.AppendLine(String.Format("#define XIO_U_MQTT_PORT          {0}", meta.MqttPort > 0 ? meta.MqttPort : 1883));
            sb.AppendLine(String.Format("#define XIO_U_MQTT_TOPIC         \"{0}\"", EscC(meta.MqttTopic)));
            sb.AppendLine(String.Format("#define XIO_U_WEBHOOK_URL        \"{0}\"", EscC(meta.WebhookUrl)));
            sb.AppendLine(String.Format("#define XIO_U_WG_ENDPOINT        \"{0}\"", EscC(meta.WireGuardEndpoint)));
            sb.AppendLine(String.Format(CultureInfo.InvariantCulture, "#define XIO_U_GEOFENCE_LAT       {0:F6}", meta.GeofenceLat));
            sb.AppendLine(String.Format(CultureInfo.InvariantCulture, "#define XIO_U_GEOFENCE_LON       {0:F6}", meta.GeofenceLon));
            sb.AppendLine(String.Format(CultureInfo.InvariantCulture, "#define XIO_U_GEOFENCE_RAD_M     {0:F1}", meta.GeofenceRadiusM > 0 ? meta.GeofenceRadiusM : 100.0));
            sb.AppendLine();

            // Seed dynamic user pin slots (0..32)
            sb.AppendLine("#define XIO_U_SEED_SLOTS(arr) do { \\");
            if (slots != null)
            {
                for (int i = 0; i < slots.Count && i < maxSlots; i++)
                {
                    PinSlotConfig s = slots[i];
                    if (s.Gpio >= 0 && s.Role > 0)
                    {
                        string lbl = EscC(s.Label);
                        if (lbl.Length > 17) lbl = lbl.Substring(0, 17);
                        sb.AppendLine(String.Format(
                            "  (arr)[{0}].gpio = {1}; (arr)[{0}].role = {2}; (arr)[{0}].param1 = {3}; (arr)[{0}].param2 = {4}; strncpy((arr)[{0}].label, \"{5}\", 17); \\",
                            i, s.Gpio, s.Role, s.Param1, s.Param2, lbl));
                    }
                }
            }
            sb.AppendLine("} while(0)");
            sb.AppendLine();

            // Seed dynamic user automation rules (0..24)
            sb.AppendLine("#define XIO_U_SEED_RULES(arr) do { \\");
            if (rules != null)
            {
                for (int i = 0; i < rules.Count && i < maxRules; i++)
                {
                    AutomationRuleConfig r = rules[i];
                    if (r.Enabled && r.Source > 0)
                    {
                        string nm = EscC(r.Name);
                        if (nm.Length > 15) nm = nm.Substring(0, 15);
                        sb.AppendLine(String.Format(CultureInfo.InvariantCulture,
                            "  (arr)[{0}].enabled = 1; (arr)[{0}].source = {1}; (arr)[{0}].op = {2}; (arr)[{0}].target_slot = {3}; (arr)[{0}].threshold = {4:F2}f; (arr)[{0}].action_val = {5}; strncpy((arr)[{0}].name, \"{6}\", 15); \\",
                            i, r.Source, r.Op, r.TargetSlot, r.Threshold, r.ActionVal, nm));
                    }
                }
            }
            sb.AppendLine("} while(0)");

            return sb.ToString();
        }

        public static string GenerateCustomUserModulesHeader(List<PuzzleFeatureItem> features)
        {
            var activeCustom = new List<PuzzleFeatureItem>();
            if (features != null)
            {
                foreach (PuzzleFeatureItem f in features)
                {
                    if (f.IsCustomUserModule && f.InActiveDeck && f.Enabled)
                        activeCustom.Add(f);
                }
            }

            var sb = new StringBuilder();
            sb.AppendLine("#pragma once");
            sb.AppendLine("#include <Arduino.h>");
            sb.AppendLine("// ============================================================================");
            sb.AppendLine("// AUTO-GENERATED USER CUSTOM C++ PUZZLE MODULES (100% USER FREEDOM)");
            sb.AppendLine(String.Format("// Active User Modules : {0}", activeCustom.Count));
            sb.AppendLine("// ============================================================================");
            sb.AppendLine();

            for (int i = 0; i < activeCustom.Count; i++)
            {
                PuzzleFeatureItem m = activeCustom[i];
                if (!string.IsNullOrEmpty(m.CustomGlobalCode))
                {
                    sb.AppendLine(String.Format("// --- [Global] {0} ---", m.Title));
                    sb.AppendLine(m.CustomGlobalCode.Trim());
                    sb.AppendLine();
                }
            }

            sb.AppendLine("static inline void xioCustomUserSetup() {");
            for (int i = 0; i < activeCustom.Count; i++)
            {
                PuzzleFeatureItem m = activeCustom[i];
                if (!string.IsNullOrEmpty(m.CustomSetupCode))
                {
                    sb.AppendLine(String.Format("  // [Setup] {0}", m.Title));
                    sb.AppendLine("  {");
                    sb.AppendLine("    " + m.CustomSetupCode.Trim().Replace("\n", "\n    "));
                    sb.AppendLine("  }");
                }
            }
            sb.AppendLine("}");
            sb.AppendLine();

            sb.AppendLine("static inline void xioCustomUserLoop() {");
            if (activeCustom.Count > 0)
                sb.AppendLine("  const uint32_t _xio_now = millis();");
            for (int i = 0; i < activeCustom.Count; i++)
            {
                PuzzleFeatureItem m = activeCustom[i];
                if (!string.IsNullOrEmpty(m.CustomLoopCode))
                {
                    int iv = m.LoopIntervalMs > 0 ? m.LoopIntervalMs : 0;
                    sb.AppendLine(String.Format("  // [Loop] {0} (interval: {1} ms)", m.Title, iv));
                    if (iv > 0)
                    {
                        sb.AppendLine(String.Format("  static uint32_t _xio_last_u{0} = 0;", i));
                        sb.AppendLine(String.Format("  if (_xio_now - _xio_last_u{0} >= {1}UL) {{", i, iv));
                        sb.AppendLine(String.Format("    _xio_last_u{0} = _xio_now;", i));
                        sb.AppendLine("    " + m.CustomLoopCode.Trim().Replace("\n", "\n    "));
                        sb.AppendLine("  }");
                    }
                    else
                    {
                        sb.AppendLine("  {");
                        sb.AppendLine("    " + m.CustomLoopCode.Trim().Replace("\n", "\n    "));
                        sb.AppendLine("  }");
                    }
                }
            }
            sb.AppendLine("}");
            sb.AppendLine();

            sb.AppendLine("String xioBuildCustomUserJson() {");
            sb.AppendLine("  String out = \"\";");
            for (int i = 0; i < activeCustom.Count; i++)
            {
                PuzzleFeatureItem m = activeCustom[i];
                string expr = (m.CustomJsonExpr ?? "").Trim();
                if (!string.IsNullOrEmpty(expr))
                {
                    string key = SafeIdent(m.Title, i + 1);
                    sb.AppendLine("  if (out.length() > 0) out += \",\";");
                    if (expr.Contains(":"))
                        sb.AppendLine(String.Format("  out += String({0});", expr));
                    else
                        sb.AppendLine(String.Format("  out += \"\\\"{0}\\\":\" + String({1});", key, expr));
                }
            }
            sb.AppendLine("  return out;");
            sb.AppendLine("}");

            return sb.ToString();
        }

        public static string DefaultAiModel(string provider)
        {
            return provider == "openrouter" ? "openai/gpt-4o-mini" : "nvidia/nemotron-3.5-bolt-e4b";
        }

        public static string ValidateAiDefaults(XioProjectFile meta)
        {
            if (meta.AiProvider != "nvidia" && meta.AiProvider != "openrouter")
                return "Pilih provider AI NVIDIA atau OpenRouter.";
            string model = meta.AiModel ?? "";
            if (model.Length > 96 || (model.Length > 0 && !Regex.IsMatch(model, @"\A[A-Za-z0-9_./:-]+\z")))
                return "Nama model AI tidak valid (maksimal 96 karakter: huruf, angka, /, -, _, ., :).";
            string key = meta.AiApiKey ?? "";
            if (key.Length == 0) return null;
            if (key.Length < 20 || key.Length > 512 || !Regex.IsMatch(key, @"\A[A-Za-z0-9_-]+\z"))
                return "API key tidak valid. Masukkan kunci saja, tanpa Bearer, spasi, atau baris baru (20..512 karakter).";
            if (meta.AiProvider == "nvidia" && !key.StartsWith("nvapi-", StringComparison.Ordinal))
                return "API key NVIDIA harus diawali nvapi-.";
            if (meta.AiProvider == "openrouter" && !key.StartsWith("sk-or-", StringComparison.Ordinal))
                return "API key OpenRouter harus diawali sk-or-.";
            return null;
        }

        public static string GenerateAiDefaultsHeader(XioProjectFile meta, bool enabled)
        {
            if (enabled)
            {
                string err = ValidateAiDefaults(meta);
                if (err != null) throw new ArgumentException(err);
            }
            string provider = enabled ? meta.AiProvider : "nvidia";
            string model = enabled && !string.IsNullOrEmpty(meta.AiModel) ? meta.AiModel : DefaultAiModel(provider);
            string key = enabled ? (meta.AiApiKey ?? "") : "";
            var sb = new StringBuilder();
            sb.AppendLine(String.Format("#define XIO_CFG_AI_PROVIDER      \"{0}\"", EscC(provider)));
            sb.AppendLine(String.Format("#define XIO_CFG_AI_MODEL         \"{0}\"", EscC(model)));
            sb.AppendLine(String.Format("#define WEBUI_AI_DEFAULT_KEY     \"{0}\"", provider == "nvidia" ? EscC(key) : ""));
            sb.AppendLine(String.Format("#define WEBUI_AI_DEFAULT_OR_KEY  \"{0}\"", provider == "openrouter" ? EscC(key) : ""));
            return sb.ToString();
        }

