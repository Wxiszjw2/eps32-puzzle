        public static string BuildUsbSlotsFormPayload(List<PinSlotConfig> slots, bool universalMode)
        {
            var parts = new List<string>();
            if (universalMode)
            {
                for (int i = 0; i < slots.Count && i < 32; i++)
                {
                    PinSlotConfig s = slots[i];
                    parts.Add(String.Format("s{0}_gpio={1}", i, s.Gpio));
                    parts.Add(String.Format("s{0}_role={1}", i, s.Role));
                    parts.Add(String.Format("s{0}_p1={1}", i, s.Param1));
                    parts.Add(String.Format("s{0}_p2={1}", i, s.Param2));
                    parts.Add(String.Format("s{0}_lbl={1}", i, Uri.EscapeDataString(s.Label ?? "")));
                }
            }
            else
            {
                var roles = StudioCatalog.GetAllRoles();
                var roleMap = new Dictionary<int, int>();
                foreach (PinRoleOption ro in roles) roleMap[ro.Code] = ro.MarauderCode;

                parts.Add("op=save_bulk");
                for (int i = 0; i < 12; i++)
                {
                    PinSlotConfig s = (slots != null && i < slots.Count) ? slots[i] : new PinSlotConfig();
                    int mRole = (s.Gpio >= 0 && roleMap.ContainsKey(s.Role)) ? roleMap[s.Role] : 0;
                    parts.Add(String.Format("g{0}={1}", i, mRole > 0 ? s.Gpio : -1));
                    parts.Add(String.Format("r{0}={1}", i, mRole));
                    parts.Add(String.Format("a{0}={1}", i, s.Param1));
                    parts.Add(String.Format("b{0}={1}", i, s.Param2));
                    parts.Add(String.Format("l{0}={1}", i, Uri.EscapeDataString(s.Label ?? "")));
                }
            }
            return string.Join("&", parts.ToArray());
        }

        public static string BuildUsbRulesFormPayload(List<AutomationRuleConfig> rules)
        {
            var parts = new List<string>();
            for (int i = 0; i < rules.Count && i < 24; i++)
            {
                AutomationRuleConfig r = rules[i];
                parts.Add(String.Format("r{0}_en={1}", i, r.Enabled ? 1 : 0));
                parts.Add(String.Format("r{0}_nm={1}", i, Uri.EscapeDataString(r.Name ?? "")));
                parts.Add(String.Format("r{0}_src={1}", i, r.Source));
                parts.Add(String.Format("r{0}_op={1}", i, r.Op));
                parts.Add(String.Format(CultureInfo.InvariantCulture, "r{0}_th={1:F2}", i, r.Threshold));
                parts.Add(String.Format("r{0}_tgt={1}", i, r.TargetSlot));
                parts.Add(String.Format("r{0}_val={1}", i, r.ActionVal));
            }
            return string.Join("&", parts.ToArray());
        }
